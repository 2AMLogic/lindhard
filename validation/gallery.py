#!/usr/bin/env python3
"""Generate the figures and tables of the book's examples gallery.

The gallery pages (book/src/gallery/) include the files under
book/src/gallery/generated/ with mdBook's {{#include}} and <img> links. Every
number and curve in them comes from a run of the `lindhard` binary on an input
under examples/; nothing is drawn by hand. This script runs the three
scenarios and rewrites those files.

  1. examples/as_50keV_si_sio2.toml: depth profile of 50 keV As through a
     10 nm SiO2 screen into Si.
  2. examples/sputtering_ar_cu_angle.toml: sputtering yield of Cu under 1 keV
     Ar against the angle of incidence. The CLI has no flag for the tilt, so
     the script writes one copy of the input per angle (only `beam.tilt_deg`
     changes) and runs it with `--seed` for several seeds.
  3. examples/electron/e_10keV_resist_on_si.toml: energy deposited by 10 keV
     electrons in a 100 nm layer on Si (SYNTHETIC electron data).
  4. examples/electron/e_dose_buried_oxide.toml: dose in a thin oxide under
     alternating metal and dielectric layers against the beam energy, 1-30
     keV (SYNTHETIC electron data). The script writes one copy of the input
     per energy (only `electron.beam.energy_ev` changes).
  5. examples/b_5keV_si.toml (the quick-start example): a few ion tracks above
     the depth profile of all the ions, on one depth axis. The CLI cannot
     record tracks, so this one runs the lindhard-wasm `Simulation` session
     under Node (one run gives both panels) and needs the Node package
     (--wasm-pkg or $LINDHARD_WASM_PKG); without it the script skips this
     figure and leaves its files as they are.

The results do not depend on the thread count, so --threads only sets the
speed (it does not apply to the Node run of figure 5, which is single-thread). The whole script takes well under a minute in a release build. The
output is deterministic for one binary and platform; floating-point
differences between platforms can change trailing digits, so the output is
regenerated by hand rather than compared in CI.

Usage: validation/gallery.py --lindhard PATH [--threads N] [--wasm-pkg DIR]

DIR is what `lindhard-wasm/build.sh nodejs DIR` writes (needs the pinned
wasm-bindgen and the wasm32-unknown-unknown target, see lindhard-wasm/README.md
and .github/workflows/wasm.yml) and `node` on the PATH. Python standard
library only (tomllib needs Python 3.11).
"""

