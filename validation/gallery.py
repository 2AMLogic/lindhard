#!/usr/bin/env python3
"""Generate the figures and tables of the book's examples gallery.

The gallery pages (book/src/gallery/) include the files under
book/src/gallery/generated/ with mdBook's {{#include}} and <img> links. Every
number and curve in them comes from a run of the `lindhard` binary on an input
under examples/; nothing is drawn by hand. This script runs the three
scenarios and rewrites those files.

  1. examples/as_50keV_si_sio2.toml: depth profile of 50 keV As through a
     10 nm SiO2 screen into Si.
  2. examples/sputtering_ar_cu_angle.toml: sputtering yield of Cu under 1 keV
     Ar against the angle of incidence. The CLI has no flag for the tilt, so
     the script writes one copy of the input per angle (only `beam.tilt_deg`
     changes) and runs it with `--seed` for several seeds.
  3. examples/electron/e_10keV_resist_on_si.toml: energy deposited by 10 keV
     electrons in a 100 nm layer on Si (SYNTHETIC electron data).

The results do not depend on the thread count, so --threads only sets the
speed. The whole script takes well under a minute in a release build. The
output is deterministic for one binary and platform; floating-point
differences between platforms can change trailing digits, so the output is
regenerated by hand rather than compared in CI.

Usage: validation/gallery.py --lindhard PATH [--threads N]

Standard library only.
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "book" / "src" / "gallery" / "generated"

SCREEN_INPUT = "examples/as_50keV_si_sio2.toml"
SPUTTER_INPUT = "examples/sputtering_ar_cu_angle.toml"
RESIST_INPUT = "examples/electron/e_10keV_resist_on_si.toml"

ANGLES_DEG = [0, 15, 30, 45, 60, 70, 80]
SEEDS = [1, 2, 3, 4]
OXIDE_NM = 10.0
RESIST_NM = 100.0

INK = "#222"
GRID = "#ddd"
BLUE = "#1f77b4"
ORANGE = "#d95f02"


def run(cmd: list[str], cwd: Path) -> None:
    proc = subprocess.run(
        cmd,
        cwd=cwd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stdout)
        raise SystemExit(f"gallery: {' '.join(cmd)} exited {proc.returncode}")


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


# ---------------------------------------------------------------------------
# A minimal SVG line/step chart
# ---------------------------------------------------------------------------


def nice_ceiling(x: float) -> float:
    """The smallest 1, 2 or 5 times a power of ten that is at least x."""
    if x <= 0:
        return 1.0
    e = math.floor(math.log10(x))
    for m in (1, 2, 5, 10):
        if m * 10**e >= x * (1 - 1e-12):
            return m * 10.0**e
    return 10.0 ** (e + 1)


def fmt(x: float) -> str:
    return f"{x:.4g}"


def chart(
    title: str,
    xlabel: str,
    ylabel: str,
    series: list[dict],
    xmax: float,
    ymax: float,
    vlines: list[tuple[float, str]] | None = None,
    band: tuple[float, float, str] | None = None,
) -> str:
    """One chart. A series is {"x": [...], "y": [...], "label": str,
    "color": str, "kind": "step" | "line", "err": [...] (optional)}. Steps
    are drawn from bin edges: x has one more entry than y."""
    w, h = 640, 380
    left, right, top, bottom = 70, 20, 40, 55
    pw, ph = w - left - right, h - top - bottom

    def sx(x: float) -> float:
        return left + pw * x / xmax

    def sy(y: float) -> float:
        return top + ph * (1 - y / ymax)

    o = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" '
        f'width="{w}" height="{h}" font-family="sans-serif" font-size="12" '
        f'role="img" aria-label="{title}">',
        f'<rect width="{w}" height="{h}" fill="#fff"/>',
        f'<text x="{w / 2}" y="22" text-anchor="middle" font-size="14" '
        f'fill="{INK}">{title}</text>',
    ]
    for i in range(6):
        gy = ymax * i / 5
        y = sy(gy)
        o.append(
            f'<line x1="{left}" x2="{left + pw}" y1="{y:.1f}" y2="{y:.1f}" '
            f'stroke="{GRID}"/>'
        )
        o.append(
            f'<text x="{left - 6}" y="{y + 4:.1f}" text-anchor="end" '
            f'fill="{INK}">{fmt(gy)}</text>'
        )
    for i in range(6):
        gx = xmax * i / 5
        x = sx(gx)
        o.append(
            f'<line x1="{x:.1f}" x2="{x:.1f}" y1="{top + ph}" y2="{top + ph + 4}" '
            f'stroke="{INK}"/>'
        )
        o.append(
            f'<text x="{x:.1f}" y="{top + ph + 18}" text-anchor="middle" '
            f'fill="{INK}">{fmt(gx)}</text>'
        )
    if band is not None:
        x0, x1, label = band
        o.append(
            f'<rect x="{sx(x0):.1f}" y="{top}" width="{sx(x1) - sx(x0):.1f}" '
            f'height="{ph}" fill="#999" fill-opacity="0.15"/>'
        )
        o.append(
            f'<text x="{(sx(x0) + sx(x1)) / 2:.1f}" y="{top + 14}" '
            f'text-anchor="middle" fill="{INK}">{label}</text>'
        )
    for xv, label in vlines or []:
        o.append(
            f'<line x1="{sx(xv):.1f}" x2="{sx(xv):.1f}" y1="{top}" '
            f'y2="{top + ph}" stroke="{INK}" stroke-dasharray="4 3"/>'
        )
        o.append(
            f'<text x="{sx(xv) + 4:.1f}" y="{top + 14}" fill="{INK}">{label}</text>'
        )
    o.append(
        f'<rect x="{left}" y="{top}" width="{pw}" height="{ph}" fill="none" '
        f'stroke="{INK}"/>'
    )
    for s in series:
        pts: list[str] = []
        if s["kind"] == "step":
            xs, ys = s["x"], s["y"]
            for i, y in enumerate(ys):
                pts.append(f"{sx(xs[i]):.1f},{sy(y):.1f}")
                pts.append(f"{sx(xs[i + 1]):.1f},{sy(y):.1f}")
        else:
            pts = [f"{sx(x):.1f},{sy(y):.1f}" for x, y in zip(s["x"], s["y"])]
        o.append(
            f'<polyline points="{" ".join(pts)}" fill="none" stroke="{s["color"]}" '
            f'stroke-width="1.8"/>'
        )
        if s["kind"] == "line":
            for i, (x, y) in enumerate(zip(s["x"], s["y"])):
                o.append(
                    f'<circle cx="{sx(x):.1f}" cy="{sy(y):.1f}" r="3.2" '
                    f'fill="{s["color"]}"/>'
                )
                if "err" in s:
                    e = s["err"][i]
                    o.append(
                        f'<line x1="{sx(x):.1f}" x2="{sx(x):.1f}" '
                        f'y1="{sy(y - e):.1f}" y2="{sy(y + e):.1f}" '
                        f'stroke="{s["color"]}"/>'
                    )
    lx, ly = left + pw - 6, top + ph - 8 - 16 * (len(series) - 1)
    for i, s in enumerate(series):
        o.append(
            f'<text x="{lx}" y="{ly + 16 * i}" text-anchor="end" '
            f'fill="{s["color"]}">{s["label"]}</text>'
        )
    o.append(
        f'<text x="{left + pw / 2}" y="{h - 12}" text-anchor="middle" '
        f'fill="{INK}">{xlabel}</text>'
    )
    o.append(
        f'<text transform="translate(16 {top + ph / 2}) rotate(-90)" '
        f'text-anchor="middle" fill="{INK}">{ylabel}</text>'
    )
    o.append("</svg>")
    return "\n".join(o) + "\n"


# ---------------------------------------------------------------------------
# The three scenarios
# ---------------------------------------------------------------------------


def screen_oxide(lindhard: Path, threads: int | None, work: Path) -> dict[str, str]:
    out = work / "screen"
    cmd = [str(lindhard), "run", SCREEN_INPUT, "--out", str(out)]
    if threads:
        cmd += ["--threads", str(threads)]
    run(cmd, ROOT)
    s = json.loads((out / "summary.json").read_text(encoding="utf-8"))
    rows = read_csv(out / "depth_profile.csv")
    # The last row is the open-ended overflow bin (upper edge "inf", no
    # per-nm density).
    rows = [r for r in rows if r["depth_hi_nm"] != "inf"]
    edges = [float(rows[0]["depth_lo_nm"])] + [float(r["depth_hi_nm"]) for r in rows]
    frac = [float(r["fraction_per_nm"]) for r in rows]
    xmax = min(edges[-1], 150.0)
    keep = [i for i in range(len(frac)) if edges[i + 1] <= xmax + 1e-9]
    svg = chart(
        "50 keV As into Si through 10 nm SiO2",
        "depth (nm)",
        "stopped As per incident ion per nm",
        [
            {
                "x": [edges[i] for i in keep] + [edges[keep[-1] + 1]],
                "y": [frac[i] for i in keep],
                "label": "lindhard, 1 nm bins",
                "color": BLUE,
                "kind": "step",
            }
        ],
        xmax,
        nice_ceiling(max(frac) * 1.1),
        vlines=[(OXIDE_NM, "SiO2 | Si")],
        band=(0.0, OXIDE_NM, ""),
    )
    r = s["results"]
    d = r["range"]["depth"]
    prim = r["primaries"]
    lay = {x["layer"]: x for x in r["range"]["layers"]}
    table = (
        "| Quantity | Value |\n|---|---|\n"
        f"| Histories, seed | {s['input']['run']['ions']}, {s['input']['run']['seed']} |\n"
        f"| Stopped, backscattered, transmitted | {prim['stopped']}, "
        f"{prim['backscattered']}, {prim['transmitted']} |\n"
        f"| Projected range R<sub>p</sub> (all stopped ions) | "
        f"{d['mean_nm']:.1f} ± {d['mean_std_err_nm']:.1f} nm |\n"
        f"| Straggle ΔR<sub>p</sub> | {d['std_dev_nm']:.1f} ± {d['std_dev_std_err_nm']:.1f} nm |\n"
        f"| Skewness, kurtosis | {d['skewness']:.2f}, {d['kurtosis']:.2f} |\n"
        f"| Stopped in the oxide, in the Si | {lay[0]['stopped']}, {lay[1]['stopped']} |\n"
        f"| Sputtered atoms per ion (all elements) | {r['sputtering']['yield_per_ion']:.2f} |\n"
    )
    return {"screen_oxide.svg": svg, "screen_oxide.md": table}


def sputter_angle(lindhard: Path, threads: int | None, work: Path) -> dict[str, str]:
    base = (ROOT / SPUTTER_INPUT).read_text(encoding="utf-8")
    if not re.search(r"^tilt_deg = 0\.0$", base, re.M):
        raise SystemExit(f"gallery: {SPUTTER_INPUT} must set tilt_deg = 0.0")
    ions = None
    results: dict[int, list[float]] = {}
    for angle in ANGLES_DEG:
        text = re.sub(
            r"^tilt_deg = 0\.0$", f"tilt_deg = {float(angle)}", base, flags=re.M
        )
        inp = work / f"sputter_{angle}.toml"
        inp.write_text(text, encoding="utf-8")
        for seed in SEEDS:
            out = work / f"sputter_{angle}_{seed}"
            cmd = [str(lindhard), "run", str(inp), "--out", str(out)]
            cmd += ["--seed", str(seed)]
            if threads:
                cmd += ["--threads", str(threads)]
            run(cmd, ROOT)
            s = json.loads((out / "summary.json").read_text(encoding="utf-8"))
            ions = s["input"]["run"]["ions"]
            results.setdefault(angle, []).append(
                s["results"]["sputtering"]["yield_per_ion"]
            )
    mean, sem = [], []
    for angle in ANGLES_DEG:
        v = results[angle]
        m = sum(v) / len(v)
        var = sum((x - m) ** 2 for x in v) / (len(v) - 1)
        mean.append(m)
        sem.append(math.sqrt(var / len(v)))
    ymax = nice_ceiling(max(m + e for m, e in zip(mean, sem)) * 1.05)
    svg = chart(
        "Sputtering yield of Cu under 1 keV Ar",
        "angle of incidence from the surface normal (degrees)",
        "sputtered Cu atoms per Ar ion",
        [
            {
                "x": [float(a) for a in ANGLES_DEG],
                "y": mean,
                "err": sem,
                "label": f"lindhard, {len(SEEDS)} seeds x {ions} ions",
                "color": ORANGE,
                "kind": "line",
            }
        ],
        90.0,
        ymax,
    )
    lines = [
        "| Angle (°) | Yield, mean of seeds | Standard error of the mean | "
        + " | ".join(f"Seed {s}" for s in SEEDS)
        + " |",
        "|---|---|---|" + "---|" * len(SEEDS),
    ]
    for angle, m, e in zip(ANGLES_DEG, mean, sem):
        lines.append(
            f"| {angle} | {m:.3f} | {e:.3f} | "
            + " | ".join(f"{x:.4f}" for x in results[angle])
            + " |"
        )
    return {"sputter_angle.svg": svg, "sputter_angle.md": "\n".join(lines) + "\n"}


def resist_on_si(lindhard: Path, threads: int | None, work: Path) -> dict[str, str]:
    out = work / "resist"
    cmd = [str(lindhard), "run", RESIST_INPUT, "--out", str(out)]
    if threads:
        cmd += ["--threads", str(threads)]
    run(cmd, ROOT)
    s = json.loads((out / "electron_summary.json").read_text(encoding="utf-8"))
    r = s["results"]
    n = r["histories"]
    rows = read_csv(out / "electron_deposition_cylindrical.csv")
    by_depth: dict[tuple[float, float], float] = {}
    for row in rows:
        k = (float(row["depth_lo_nm"]), float(row["depth_hi_nm"]))
        by_depth[k] = by_depth.get(k, 0.0) + float(row["energy_ev"])
    keys = sorted(by_depth)
    edges = [keys[0][0]] + [k[1] for k in keys]
    b = r["budget"]
    layer_ev = r["deposition"]["per_layer_ev"]
    # The library measures deposited energy from the band bottom, so it
    # includes the Fermi-sea energy of liberated conduction electrons
    # (docs/cli.md, "electron_summary.json"). The profile is therefore shown
    # as a share of the total deposited, not in eV per electron.
    total = b["deposited_ev"]
    per_nm = [100.0 * by_depth[k] / total / (k[1] - k[0]) for k in keys]
    svg = chart(
        "10 keV electrons, 100 nm resist on Si (synthetic data)",
        "depth (nm)",
        "share of deposited energy (% per nm)",
        [
            {
                "x": edges,
                "y": per_nm,
                "label": f"lindhard, 50 nm bins, {n} histories",
                "color": BLUE,
                "kind": "step",
            }
        ],
        edges[-1],
        nice_ceiling(max(per_nm) * 1.1),
        vlines=[(RESIST_NM, "resist | Si")],
        band=(0.0, RESIST_NM, ""),
    )
    inc = b["incident_ev"]
    y = r["yields"]
    inside = sum(by_depth.values())
    table = (
        "| Quantity | Value |\n|---|---|\n"
        f"| Histories, seed | {n}, {s['input']['run']['seed']} |\n"
        f"| Incident minus escaped energy | {100 * (inc - b['escaped_ev']) / inc:.1f} % of the beam energy |\n"
        f"| Deposited energy (band-bottom reference) | {100 * total / inc:.1f} % of the beam energy |\n"
        f"| of which Fermi-sea energy of liberated conduction electrons | {100 * b['fermi_sea_ev'] / inc:.1f} % |\n"
        f"| Share of the deposited energy in the resist, in the Si | {100 * layer_ev[0] / total:.1f} %, {100 * layer_ev[1] / total:.1f} % |\n"
        f"| Share inside the scoring grid (1000 nm radius, 1500 nm depth) | {100 * inside / total:.1f} % |\n"
        f"| Backscatter coefficient η, secondary yield δ | {y['backscatter_eta']:.3f}, {y['secondary_delta']:.3f} |\n"
        f"| Energy balance, relative imbalance | {b['relative_imbalance']:.1e} |\n"
    )
    return {"resist_on_si.svg": svg, "resist_on_si.md": table}


def generate(lindhard: Path, threads: int | None) -> dict[str, str]:
    files: dict[str, str] = {}
    with tempfile.TemporaryDirectory(prefix="lindhard-gallery-") as tmp:
        work = Path(tmp)
        files.update(screen_oxide(lindhard, threads, work))
        files.update(sputter_angle(lindhard, threads, work))
        files.update(resist_on_si(lindhard, threads, work))
    return files


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument(
        "--lindhard", required=True, type=Path, help="path to the lindhard binary"
    )
    ap.add_argument(
        "--threads",
        type=int,
        default=None,
        help="worker threads (does not change results)",
    )
    args = ap.parse_args(argv)
    files = generate(args.lindhard.resolve(), args.threads)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT_DIR / name).write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} files to {OUT_DIR.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
