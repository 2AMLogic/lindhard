def screen_oxide(lindhard: Path, threads: int | None, work: Path) -> dict[str, str]:
    out = work / "screen"
    cmd = [str(lindhard), "run", SCREEN_INPUT, "--out", str(out)]
    if threads:
        cmd += ["--threads", str(threads)]
    run(cmd, ROOT)
    s = json.loads((out / "summary.json").read_text(encoding="utf-8"))
    rows = read_csv(out / "depth_profile.csv")
    # The last row is the open-ended overflow bin (upper edge "inf", no
    # per-nm density).
    rows = [r for r in rows if r["depth_hi_nm"] != "inf"]
    edges = [float(rows[0]["depth_lo_nm"])] + [float(r["depth_hi_nm"]) for r in rows]
    frac = [float(r["fraction_per_nm"]) for r in rows]
    xmax = min(edges[-1], 150.0)
    keep = [i for i in range(len(frac)) if edges[i + 1] <= xmax + 1e-9]
    svg = chart(
        "50 keV As into Si through 10 nm SiO2",
        "depth (nm)",
        "stopped As per incident ion per nm",
        [
            {
                "x": [edges[i] for i in keep] + [edges[keep[-1] + 1]],
                "y": [frac[i] for i in keep],
                "label": "lindhard, 1 nm bins",
                "color": BLUE,
                "kind": "step",
            }
        ],
        xmax,
        nice_ceiling(max(frac) * 1.1),
        vlines=[(OXIDE_NM, "SiO2 | Si")],
        band=(0.0, OXIDE_NM, ""),
    )
    r = s["results"]
    d = r["range"]["depth"]
    prim = r["primaries"]
    lay = {x["layer"]: x for x in r["range"]["layers"]}
    table = (
        "| Quantity | Value |\n|---|---|\n"
        f"| Histories, seed | {s['input']['run']['ions']}, {s['input']['run']['seed']} |\n"
        f"| Stopped, backscattered, transmitted | {prim['stopped']}, "
        f"{prim['backscattered']}, {prim['transmitted']} |\n"
        f"| Projected range R<sub>p</sub> (all stopped ions) | "
        f"{d['mean_nm']:.1f} ± {d['mean_std_err_nm']:.1f} nm |\n"
        f"| Straggle ΔR<sub>p</sub> | {d['std_dev_nm']:.1f} ± {d['std_dev_std_err_nm']:.1f} nm |\n"
        f"| Skewness, kurtosis | {d['skewness']:.2f}, {d['kurtosis']:.2f} |\n"
        f"| Stopped in the oxide, in the Si | {lay[0]['stopped']}, {lay[1]['stopped']} |\n"
        f"| Sputtered atoms per ion (all elements) | {r['sputtering']['yield_per_ion']:.2f} |\n"
    )
    return {"screen_oxide.svg": svg, "screen_oxide.md": table}


def sputter_angle(lindhard: Path, threads: int | None, work: Path) -> dict[str, str]:
    base = (ROOT / SPUTTER_INPUT).read_text(encoding="utf-8")
    if not re.search(r"^tilt_deg = 0\.0$", base, re.M):
        raise SystemExit(f"gallery: {SPUTTER_INPUT} must set tilt_deg = 0.0")
    ions = None
    results: dict[int, list[float]] = {}
    for angle in ANGLES_DEG:
        text = re.sub(
            r"^tilt_deg = 0\.0$", f"tilt_deg = {float(angle)}", base, flags=re.M
        )
        inp = work / f"sputter_{angle}.toml"
        inp.write_text(text, encoding="utf-8")
        for seed in SEEDS:
            out = work / f"sputter_{angle}_{seed}"
            cmd = [str(lindhard), "run", str(inp), "--out", str(out)]
            cmd += ["--seed", str(seed)]
            if threads:
                cmd += ["--threads", str(threads)]
            run(cmd, ROOT)
            s = json.loads((out / "summary.json").read_text(encoding="utf-8"))
            ions = s["input"]["run"]["ions"]
            results.setdefault(angle, []).append(
                s["results"]["sputtering"]["yield_per_ion"]
            )
    mean, sem = [], []
    for angle in ANGLES_DEG:
        v = results[angle]
        m = sum(v) / len(v)
        var = sum((x - m) ** 2 for x in v) / (len(v) - 1)
        mean.append(m)
        sem.append(math.sqrt(var / len(v)))
    ymax = nice_ceiling(max(m + e for m, e in zip(mean, sem)) * 1.05)
    svg = chart(
        "Sputtering yield of Cu under 1 keV Ar",
        "angle of incidence from the surface normal (degrees)",
        "sputtered Cu atoms per Ar ion",
        [
            {
                "x": [float(a) for a in ANGLES_DEG],
                "y": mean,
                "err": sem,
                "label": f"lindhard, {len(SEEDS)} seeds x {ions} ions",
                "color": ORANGE,
                "kind": "line",
            }
        ],
        90.0,
        ymax,
    )
    lines = [
        "| Angle (°) | Yield, mean of seeds | Standard error of the mean | "
        + " | ".join(f"Seed {s}" for s in SEEDS)
        + " |",
        "|---|---|---|" + "---|" * len(SEEDS),
    ]
    for angle, m, e in zip(ANGLES_DEG, mean, sem):
        lines.append(
            f"| {angle} | {m:.3f} | {e:.3f} | "
            + " | ".join(f"{x:.4f}" for x in results[angle])
            + " |"
        )
    return {"sputter_angle.svg": svg, "sputter_angle.md": "\n".join(lines) + "\n"}


def resist_on_si(lindhard: Path, threads: int | None, work: Path) -> dict[str, str]:
    out = work / "resist"
    cmd = [str(lindhard), "run", RESIST_INPUT, "--out", str(out)]
    if threads:
        cmd += ["--threads", str(threads)]
    run(cmd, ROOT)
    s = json.loads((out / "electron_summary.json").read_text(encoding="utf-8"))
    r = s["results"]
    n = r["histories"]
    rows = read_csv(out / "electron_deposition_cylindrical.csv")
    by_depth: dict[tuple[float, float], float] = {}
    for row in rows:
        k = (float(row["depth_lo_nm"]), float(row["depth_hi_nm"]))
        by_depth[k] = by_depth.get(k, 0.0) + float(row["energy_ev"])
    keys = sorted(by_depth)
    edges = [keys[0][0]] + [k[1] for k in keys]
    b = r["budget"]
    layer_ev = r["deposition"]["per_layer_ev"]
    # The library measures deposited energy from the band bottom, so it
    # includes the Fermi-sea energy of liberated conduction electrons
    # (docs/cli.md, "electron_summary.json"). The profile is therefore shown
    # as a share of the total deposited, not in eV per electron.
    total = b["deposited_ev"]
    per_nm = [100.0 * by_depth[k] / total / (k[1] - k[0]) for k in keys]
    svg = chart(
        "10 keV electrons, 100 nm resist on Si (synthetic data)",
        "depth (nm)",
        "share of deposited energy (% per nm)",
        [
            {
                "x": edges,
                "y": per_nm,
                "label": f"lindhard, 50 nm bins, {n} histories",
                "color": BLUE,
                "kind": "step",
            }
        ],
        edges[-1],
        nice_ceiling(max(per_nm) * 1.1),
        vlines=[(RESIST_NM, "resist | Si")],
        band=(0.0, RESIST_NM, ""),
    )
    inc = b["incident_ev"]
    y = r["yields"]
    inside = sum(by_depth.values())
    table = (
        "| Quantity | Value |\n|---|---|\n"
        f"| Histories, seed | {n}, {s['input']['run']['seed']} |\n"
        f"| Incident minus escaped energy | {100 * (inc - b['escaped_ev']) / inc:.1f} % of the beam energy |\n"
        f"| Deposited energy (band-bottom reference) | {100 * total / inc:.1f} % of the beam energy |\n"
        f"| of which Fermi-sea energy of liberated conduction electrons | {100 * b['fermi_sea_ev'] / inc:.1f} % |\n"
        f"| Share of the deposited energy in the resist, in the Si | {100 * layer_ev[0] / total:.1f} %, {100 * layer_ev[1] / total:.1f} % |\n"
        f"| Share inside the scoring grid (1000 nm radius, 1500 nm depth) | {100 * inside / total:.1f} % |\n"
        f"| Backscatter coefficient η, secondary yield δ | {y['backscatter_eta']:.3f}, {y['secondary_delta']:.3f} |\n"
        f"| Energy balance, relative imbalance | {b['relative_imbalance']:.1e} |\n"
    )
    return {"resist_on_si.svg": svg, "resist_on_si.md": table}


def dose_buried_oxide(lindhard: Path, threads: int | None, work: Path) -> dict[str, str]:
    src = ROOT / DOSE_INPUT
    text = src.read_text(encoding="utf-8")
    # The data files are named relative to the input, so the copies sit next
    # to it, in the work directory, with the ELF alongside.
    (work / "synthetic_plasmon_elf.toml").write_text(
        (src.parent / "synthetic_plasmon_elf.toml").read_text(encoding="utf-8"),
        encoding="utf-8",
    )
    # Dose per unit fluence, reported for a fluence of 1e12 electrons/cm^2.
    fluence_m2 = 1e12 * 1e4
    energies: list[float] = []
    dose: list[float] = []
    err: list[float] = []
    rows_md = []
    n = None
    for kev in DOSE_ENERGIES_KEV:
        new, count = re.subn(
            r"^energy_ev = [0-9.eE+-]+$", f"energy_ev = {kev * 1000.0}", text, flags=re.M
        )
        assert count == 1, "beam energy line not found"
        inp = work / f"dose_{kev}keV.toml"
        inp.write_text(new, encoding="utf-8")
        out = work / f"dose_{kev}keV"
        cmd = [str(lindhard), "run", str(inp), "--out", str(out)]
        if threads:
            cmd += ["--threads", str(threads)]
        run(cmd, ROOT)
        s = json.loads((out / "electron_summary.json").read_text(encoding="utf-8"))
        n = s["results"]["histories"]
        layers = s["results"]["dose"]["layers"]
        ox = next(l for l in layers if l["name"] == "Oxide")
        d, e = ox["dose_gy_m2"]["mean"] * fluence_m2, ox["dose_gy_m2"]["std_err"] * fluence_m2
        energies.append(float(kev))
        dose.append(d)
        err.append(e)
        rows_md.append(f"| {kev} | {d:.3g} ± {e:.2g} |")
    top = max(d + e for d, e in zip(dose, err))
    svg = chart(
        "Dose in the buried oxide against beam energy (synthetic data)",
        "beam energy (keV)",
        "dose in the oxide (Gy) at 1e12 electrons/cm²",
        [
            {
                "x": energies,
                "y": dose,
                "err": err,
                "label": f"lindhard, {n} histories per point",
                "color": BLUE,
                "kind": "line",
            }
        ],
        max(energies),
        nice_ceiling(top * 1.1),
    )
    table = (
        "| Beam energy (keV) | Dose in the oxide (Gy), mean ± standard error |\n|---|---|\n"
        + "\n".join(rows_md)
        + "\n"
    )
    return {"dose_buried_oxide.svg": svg, "dose_buried_oxide.md": table}


# Run by `node`: one Simulation session; prints the report and the recorded
# histories of that one run as JSON on stdout.
NODE_SESSION = """
const { readFileSync } = require("node:fs");
const [pkg, input, record, maxPoints] = process.argv.slice(2);
const wasm = require(pkg + "/lindhard_wasm.js");
const sim = new wasm.Simulation(readFileSync(input, "utf8"), +record, +maxPoints);
while (!sim.done()) sim.step(1000);
process.stdout.write(JSON.stringify({
  report: JSON.parse(sim.report_json()),
  tracks: JSON.parse(sim.take_trajectories_json()),
  warnings: sim.warnings(),
}));
sim.free();
"""


def kev(ev: float) -> str:
    return f"{ev / 1000.0:g} keV"


def quickstart(wasm_pkg: Path, work: Path) -> dict[str, str]:
    node = shutil.which("node")
    if node is None:
        raise SystemExit("gallery: the quickstart figure needs `node` on the PATH")
    if not (wasm_pkg / "lindhard_wasm.js").is_file():
        raise SystemExit(
            f"gallery: {wasm_pkg}/lindhard_wasm.js not found; build the Node "
            "package with `lindhard-wasm/build.sh nodejs <dir>` and pass <dir>"
        )
    script = work / "quickstart_session.cjs"
    script.write_text(NODE_SESSION, encoding="utf-8")
    inp = ROOT / QUICKSTART_INPUT
    proc = subprocess.run(
        [node, str(script), str(wasm_pkg), str(inp), str(QUICKSTART_TRACKS),
         str(QUICKSTART_MAX_POINTS)],
        cwd=work, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
        check=False,
    )
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr)
        raise SystemExit(f"gallery: the wasm session exited {proc.returncode}")
    session = json.loads(proc.stdout)
    report, warnings = session["report"], session["warnings"]
    if warnings:
        raise SystemExit(f"gallery: the quickstart run has warnings: {warnings}")
    spec = tomllib.loads(inp.read_text(encoding="utf-8"))

    # Panel 2: the depth histogram of all the histories, per incident ion per
    # nm (as depth_profile.csv's fraction_per_nm). Lengths from the session
    # are in metres.
    hist = report["range"]["depth_histogram"]
    b = hist["binning"]
    n_ions = report["histories"]
    step_nm = (b["hi"] - b["lo"]) / b["bins"] * 1e9
    edges = [b["lo"] * 1e9 + i * step_nm for i in range(b["bins"] + 1)]
    frac = [c / n_ions / step_nm for c in hist["counts"]]

    # Panel 1: the primary ion (generation 0) of each recorded history, as
    # (depth, lateral y) in nm. A track that leaves through the surface is cut
    # where it crosses depth 0.
    paths: list[tuple[list[float], list[float]]] = []
    for h in session["tracks"]["histories"]:
        if h["truncated"]:
            raise SystemExit(f"gallery: history {h['index']} hit the point cap")
        (t,) = [t for t in h["tracks"] if t["generation"] == 0]
        xs: list[float] = []
        ys: list[float] = []
        prev = None
        for x, y, _z, _e in t["points"]:
            x, y = x * 1e9, y * 1e9
            if x < 0:
                if prev is not None and prev[0] > 0:
                    f = prev[0] / (prev[0] - x)
                    xs.append(0.0)
                    ys.append(prev[1] + f * (y - prev[1]))
                break
            xs.append(x)
            ys.append(y)
            prev = (x, y)
        paths.append((xs, ys))
    if len(paths) != QUICKSTART_TRACKS:
        raise SystemExit(f"gallery: expected {QUICKSTART_TRACKS} recorded histories")

    # The shared depth axis ends at the next 10 nm above the deepest track or
    # non-empty histogram bin.
    last = max(i for i, c in enumerate(hist["counts"]) if c > 0)
    deepest = max(edges[last + 1], max(max(xs) for xs, _ in paths))
    xmax = 10.0 * math.ceil(deepest / 10.0 - 1e-9)
    keep = [i for i in range(b["bins"]) if edges[i + 1] <= xmax + 1e-9]
    edges, frac = edges[: keep[-1] + 2], frac[: keep[-1] + 1]
    lat = nice_ceiling(max(abs(y) for _, ys in paths for y in ys) * 1.05)
    ymax2 = nice_ceiling(max(frac) * 1.1)
    ion, energy = spec["beam"]["ion"], spec["beam"]["energy_ev"]
    title = f"{kev(energy)} {ion} into {spec['target']['substrate']}"
    w, h = 640, 530
    left, right = 70, 20
    pw = w - left - right
    o = svg_open(w, h, title)
    panel(
        o, left, 40, pw, 200, None,
        "lateral y (nm)",
        [{"paths": paths, "label": f"{QUICKSTART_TRACKS} recorded ions",
          "color": BLUE, "kind": "paths"}],
        xmax, lat, ymin=-lat, yintervals=4,
    )
    panel(
        o, left, 270, pw, 200, "depth (nm)",
        "stopped per ion per nm",
        [{"x": edges, "y": frac,
          "label": f"all {n_ions} ions, {fmt(step_nm)} nm bins",
          "color": ORANGE, "kind": "step"}],
        xmax, ymax2,
    )
    o.append("</svg>")
    svg = "\n".join(o) + "\n"

    d = report["range"]["depth"]
    phys = spec["physics"]
    models = ", ".join(
        f"{label} {phys[k]}"
        for label, k in (
            ("potential", "potential"),
            ("stopping", "stopping"),
            ("free path", "free_path"),
        )
    )
    caption = (
        f"{title}, {fmt(spec['beam'].get('tilt_deg', 0.0))}° from the surface "
        f"normal: {n_ions} ions, seed {spec['run']['seed']}; models: {models}. "
        f"Top: the paths of the first {QUICKSTART_TRACKS} ions (depth against "
        f"lateral y; the two axes have different scales). Bottom: where all {n_ions} ions stopped; "
        f"{report['range']['stopped']} stopped in the target, R<sub>p</sub> = "
        f"{d['mean'] * 1e9:.1f} ± {d['mean_std_err'] * 1e9:.1f} nm, "
        f"ΔR<sub>p</sub> = {d['std_dev'] * 1e9:.1f} nm. Both panels are one run "
        f"of `{QUICKSTART_INPUT}`.\n"
    )
    return {"quickstart.svg": svg, "quickstart.md": caption}


def generate(
    lindhard: Path, threads: int | None, wasm_pkg: Path | None
) -> dict[str, str]:
    files: dict[str, str] = {}
    with tempfile.TemporaryDirectory(prefix="lindhard-gallery-") as tmp:
        work = Path(tmp)
        files.update(screen_oxide(lindhard, threads, work))
        files.update(sputter_angle(lindhard, threads, work))
        files.update(resist_on_si(lindhard, threads, work))
        files.update(dose_buried_oxide(lindhard, threads, work))
        if wasm_pkg is not None:
            files.update(quickstart(wasm_pkg, work))
        else:
            print(
                "gallery: no --wasm-pkg / $LINDHARD_WASM_PKG; skipping the "
                "quickstart figure",
                file=sys.stderr,
            )
    return files


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument(
        "--lindhard", required=True, type=Path, help="path to the lindhard binary"
    )
    ap.add_argument(
        "--threads",
        type=int,
        default=None,
        help="worker threads (does not change results)",
    )
    ap.add_argument(
        "--wasm-pkg",
        type=Path,
        default=None,
        help="Node package of lindhard-wasm (lindhard-wasm/build.sh nodejs DIR); "
        "default $LINDHARD_WASM_PKG; the quickstart figure is skipped without it",
    )
    args = ap.parse_args(argv)
    pkg = args.wasm_pkg or (
        Path(os.environ["LINDHARD_WASM_PKG"])
        if os.environ.get("LINDHARD_WASM_PKG")
        else None
    )
    files = generate(
        args.lindhard.resolve(), args.threads, pkg.resolve() if pkg else None
    )
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT_DIR / name).write_text(text, encoding="utf-8")
    print(f"wrote {len(files)} files to {OUT_DIR.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
