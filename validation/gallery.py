def nice_ceiling(x: float) -> float:
    """The smallest 1, 2 or 5 times a power of ten that is at least x."""
    if x <= 0:
        return 1.0
    e = math.floor(math.log10(x))
    for m in (1, 2, 5, 10):
        if m * 10**e >= x * (1 - 1e-12):
            return m * 10.0**e
    return 10.0 ** (e + 1)


def fmt(x: float) -> str:
    return f"{x:.4g}"


def svg_open(w: int, h: int, title: str) -> list[str]:
    """The opening of a figure: <svg>, the dark-scheme style, the plate and
    the title."""
    return [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" '
        f'width="{w}" height="{h}" font-family="sans-serif" font-size="12" '
        f'role="img" aria-label="{title}">',
        dark_style(),
        f'<rect width="{w}" height="{h}" fill="#fff"/>',
        f'<text x="{w / 2}" y="22" text-anchor="middle" font-size="14" '
        f'fill="{INK}">{title}</text>',
    ]


def panel(
    o: list[str],
    left: float,
    top: float,
    pw: float,
    ph: float,
    xlabel: str | None,
    ylabel: str,
    series: list[dict],
    xmax: float,
    ymax: float,
    ymin: float = 0.0,
    vlines: list[tuple[float, str]] | None = None,
    band: tuple[float, float, str] | None = None,
    yintervals: int = 5,
) -> None:
    """Append one plot panel (axes, grid, series, legend, labels) to the SVG
    element list `o`; its plot area is pw x ph with its corner at (left, top).
    A series is {"x": [...], "y": [...], "label": str, "color": str,
    "kind": "step" | "line" | "paths", "err": [...] (optional)}. Steps are
    drawn from bin edges: x has one more entry than y. A "paths" series has
    "paths": [(xs, ys), ...] instead of x and y. With xlabel None the panel
    has no x tick marks or labels (it shares the axis of the panel below)."""

    def sx(x: float) -> float:
        return left + pw * x / xmax

    def sy(y: float) -> float:
        return top + ph * (1 - (y - ymin) / (ymax - ymin))

    for i in range(yintervals + 1):
        gy = ymin + (ymax - ymin) * i / yintervals
        y = sy(gy)
        o.append(
            f'<line x1="{left}" x2="{left + pw}" y1="{y:.1f}" y2="{y:.1f}" '
            f'stroke="{GRID}"/>'
        )
        o.append(
            f'<text x="{left - 6}" y="{y + 4:.1f}" text-anchor="end" '
            f'fill="{INK}">{fmt(gy)}</text>'
        )
    for i in range(6 if xlabel is not None else 0):
        gx = xmax * i / 5
        x = sx(gx)
        o.append(
            f'<line x1="{x:.1f}" x2="{x:.1f}" y1="{top + ph}" y2="{top + ph + 4}" '
            f'stroke="{INK}"/>'
        )
        o.append(
            f'<text x="{x:.1f}" y="{top + ph + 18}" text-anchor="middle" '
            f'fill="{INK}">{fmt(gx)}</text>'
        )
    if band is not None:
        x0, x1, label = band
        o.append(
            f'<rect x="{sx(x0):.1f}" y="{top}" width="{sx(x1) - sx(x0):.1f}" '
            f'height="{ph}" fill="#999" fill-opacity="0.15"/>'
        )
        o.append(
            f'<text x="{(sx(x0) + sx(x1)) / 2:.1f}" y="{top + 14}" '
            f'text-anchor="middle" fill="{INK}">{label}</text>'
        )
    for xv, label in vlines or []:
        o.append(
            f'<line x1="{sx(xv):.1f}" x2="{sx(xv):.1f}" y1="{top}" '
            f'y2="{top + ph}" stroke="{INK}" stroke-dasharray="4 3"/>'
        )
        o.append(
            f'<text x="{sx(xv) + 4:.1f}" y="{top + 14}" fill="{INK}">{label}</text>'
        )
    o.append(
        f'<rect x="{left}" y="{top}" width="{pw}" height="{ph}" fill="none" '
        f'stroke="{INK}"/>'
    )
    for s in series:
        if s["kind"] == "paths":
            for xs, ys in s["paths"]:
                pts = " ".join(f"{sx(x):.1f},{sy(y):.1f}" for x, y in zip(xs, ys))
                o.append(
                    f'<polyline points="{pts}" fill="none" stroke="{s["color"]}" '
                    f'stroke-width="1" stroke-opacity="0.8"/>'
                )
            continue
        pts: list[str] = []
        if s["kind"] == "step":
            xs, ys = s["x"], s["y"]
            for i, y in enumerate(ys):
                pts.append(f"{sx(xs[i]):.1f},{sy(y):.1f}")
                pts.append(f"{sx(xs[i + 1]):.1f},{sy(y):.1f}")
        else:
            pts = [f"{sx(x):.1f},{sy(y):.1f}" for x, y in zip(s["x"], s["y"])]
        o.append(
            f'<polyline points="{" ".join(pts)}" fill="none" stroke="{s["color"]}" '
            f'stroke-width="1.8"/>'
        )
        if s["kind"] == "line":
            for i, (x, y) in enumerate(zip(s["x"], s["y"])):
                o.append(
                    f'<circle cx="{sx(x):.1f}" cy="{sy(y):.1f}" r="3.2" '
                    f'fill="{s["color"]}"/>'
                )
                if "err" in s:
                    e = s["err"][i]
                    o.append(
                        f'<line x1="{sx(x):.1f}" x2="{sx(x):.1f}" '
                        f'y1="{sy(y - e):.1f}" y2="{sy(y + e):.1f}" '
                        f'stroke="{s["color"]}"/>'
                    )
    lx, ly = left + pw - 6, top + ph - 8 - 16 * (len(series) - 1)
    for i, s in enumerate(series):
        o.append(
            f'<text x="{lx}" y="{ly + 16 * i}" text-anchor="end" '
            f'fill="{s["color"]}">{s["label"]}</text>'
        )
    if xlabel is not None:
        o.append(
            f'<text x="{left + pw / 2}" y="{top + ph + 43}" text-anchor="middle" '
            f'fill="{INK}">{xlabel}</text>'
        )
    o.append(
        f'<text transform="translate(16 {top + ph / 2}) rotate(-90)" '
        f'text-anchor="middle" fill="{INK}">{ylabel}</text>'
    )


def chart(
    title: str,
    xlabel: str,
    ylabel: str,
    series: list[dict],
    xmax: float,
    ymax: float,
    vlines: list[tuple[float, str]] | None = None,
    band: tuple[float, float, str] | None = None,
) -> str:
    """One chart: a single panel on a 640 x 380 plate (see panel)."""
    w, h = 640, 380
    left, right, top, bottom = 70, 20, 40, 55
    o = svg_open(w, h, title)
    panel(
        o, left, top, w - left - right, h - top - bottom, xlabel, ylabel,
        series, xmax, ymax, vlines=vlines, band=band,
    )
    o.append("</svg>")
    return "\n".join(o) + "\n"


