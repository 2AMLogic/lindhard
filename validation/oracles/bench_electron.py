# docs/benchmarks.md


def _fmt(x, digits=3):
    if x is None:
        return "n/a"
    return f"{x:.{digits}g}"


def doc_tables() -> str:
    spec = json.loads(run_electron.PROBLEMS.read_text())
    order = [p["id"] for p in spec["problems"]]
    lines = []
    benches = sorted(SUMMARIES.glob("bench-electron-*.json"),
                     key=lambda p: order.index(p.stem.removeprefix("bench-electron-"))
                     if p.stem.removeprefix("bench-electron-") in order else 99)
    lines.append("**lindhard, thread scaling** (`bench-electron-<problem>.json`; transport only, tables "
                 "built once beforehand; median of the repeats; efficiency = speedup x 1 / threads).")
    lines.append("")
    lines.append("| Problem | Histories | Threads | Wall (s) | Electrons/s | Speedup | Efficiency | "
                 "Same report | Tables (s): elastic + inelastic | Load at start / end | Host, date |")
    lines.append("|---|---|---|---|---|---|---|---|---|---|---|")
    pending = set()
    for path in benches:
        s = json.loads(path.read_text())
        h = s["host"]
        host_s = (f"{h.get('cpu_model') or h.get('machine')}, {h.get('physical_cores')} cores / "
                  f"{h.get('logical_cpus')} threads; {s['date']}")
        lin = s["lindhard"]
        tb = lin["tables"]
        measured = {r["threads"] for r in lin["runs"]}
        for r in lin["runs"]:
            lines.append(
                f"| `{s['problem']}` | {lin['histories']} | {r['threads']} | {_fmt(r['wall_s_median'])} | "
                f"{_fmt(r['electrons_per_s'])} | {_fmt(r['speedup'])} | {_fmt(r['efficiency'])} | "
                f"{'yes' if r['identical_to_first'] else '**no**'} | "
                f"{_fmt(tb['elastic_s'])} + {_fmt(tb['inelastic_s'])} | "
                f"{_fmt(s['load_average']['start'])} / {_fmt(s['load_average']['end'])} | {host_s} |")
        cores = h.get("physical_cores") or 0
        n = 1
        while n <= cores:
            if n not in measured:
                pending.add(n)
            n *= 2
        if cores and cores not in measured:
            pending.add(cores)
    if pending:
        lines.append("")
        lines.append("Not measured (placeholders, see the caveats below): "
                     + ", ".join(f"{n} threads" for n in sorted(pending))
                     + " on every problem.")
    lines.append("")

    nebs = [json.loads(p.read_text()) for p in benches]
    nebs = [s for s in nebs if s.get("nebula")]
    lines.append("**lindhard vs Nebula CPU, transport rate** (`bench-electron-<problem>.json`):")
    lines.append("")
    if nebs:
        lines.append("| Problem | Threads | lindhard electrons/s | Nebula electrons/s | Ratio (lindhard / Nebula) | "
                     "Nebula version | Load at start |")
        lines.append("|---|---|---|---|---|---|---|")
        for s in nebs:
            c = s.get("comparison") or {}
            lines.append(
                f"| `{s['problem']}` | {s['nebula']['threads']} | {_fmt(c.get('lindhard_electrons_per_s'))} | "
                f"{_fmt(s['nebula']['electrons_per_s'])} | {_fmt(c.get('electrons_per_s_ratio'))} | "
                f"{s['nebula'].get('version')} | {_fmt(s['load_average']['start'])} |")
    else:
        lines.append("Not measured yet: no `bench-electron-*.json` summary has a Nebula timing (see the caveats).")
    lines.append("")

    lines.append("**End-to-end wall time of the #150 comparison runs** (`nebula-<problem>.json`, `wall_s`; not "
                 "re-run here). lindhard: 10 batch processes, each building its tables and running a tenth of the "
                 "histories; Nebula: one process, material loading included, its deposit stream read by "
                 "`run_electron.py`. Not a transport-rate comparison.")
    lines.append("")
    lines.append("| Problem | Histories | lindhard wall (s) | Nebula wall (s) | Nebula end-to-end electrons/s | "
                 "Nebula version | Host, load at start, date |")
    lines.append("|---|---|---|---|---|---|---|")
    for pid in order:
        path = SUMMARIES / f"nebula-{pid}.json"
        if not path.is_file():
            continue
        s = json.loads(path.read_text())
        n = s["histories"]["oracle"]
        w = s["wall_s"]
        lines.append(f"| `{pid}` | {n} | {_fmt(w['lindhard'], 4)} | {_fmt(w['oracle'], 4)} | "
                     f"{_fmt(n / w['oracle'] if w['oracle'] else None)} | {s['oracle_version']} | "
                     f"{s['host']}, {s['date']} |")
    return "\n".join(lines)


def update_docs(check: bool = False) -> int:
    """Rewrite the block between the markers; with `check`, only compare."""
    text = DOC.read_text()
    if BEGIN not in text or END not in text:
        lindhard_cli.die(f"{DOC}: markers not found")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + BEGIN + "\n" + doc_tables() + "\n" + END + tail
    if check:
        if new != text:
            print(f"{DOC.relative_to(lindhard_cli.REPO)} is out of date: run "
                  "validation/oracles/bench_electron.py --update-docs", file=sys.stderr)
            return 1
        return 0
    DOC.write_text(new)
    print(f"updated {DOC.relative_to(lindhard_cli.REPO)}")
    return 0


# ---------------------------------------------------------------------------


def _round(x):
    return run_electron._round(x)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--problem", action="append", help="problem id (repeatable)")
    ap.add_argument("--threads", help="thread counts, e.g. 1,2,4 (default: 1, 2, 4, ... up to the physical cores)")
    ap.add_argument("--repeat", type=int, default=3, help="transport runs per thread count (median reported)")
    ap.add_argument("--table-threads", type=int, default=1, help="threads of the table build")
    ap.add_argument("--scale", type=float, default=1.0, help="multiply every history count")
    ap.add_argument("--lindhard-only", action="store_true", help="do not time Nebula")
    ap.add_argument("--write-inputs", action="store_true", help="write the matched inputs and stop")
    ap.add_argument("--update-docs", action="store_true", help="rebuild the docs tables and stop")
    ap.add_argument("--check", action="store_true",
                    help="with --update-docs: exit 1 if the docs differ, write nothing (CI)")
    args = ap.parse_args()

    if args.update_docs:
        return update_docs(check=args.check)

    spec = json.loads(run_electron.PROBLEMS.read_text())
    problems = [p for p in spec["problems"] if not args.problem or p["id"] in args.problem]
    if not problems:
        lindhard_cli.die(f"no problem matches {args.problem}")
    src = os.environ.get("CSTOOL_SRC")
    if not src:
        print("CSTOOL_SRC not set: the material parameters come from cstool's files (see run_electron.py); "
              "nothing run")
        return 0
    cstool = Path(src)

    h = host()
    if args.threads:
        threads = [int(t) for t in args.threads.split(",")]
    else:
        cores = h["physical_cores"] or h["logical_cpus"] or 1
        threads, n = [], 1
        while n < cores:
            threads.append(n)
            n *= 2
        threads.append(cores)

    if args.write_inputs:
        for p in problems:
            path, _ = write_input(p, spec, cstool, p["histories"])
            print(f"wrote {path}")
        print(f"LINDHARD_BENCH_ELECTRON_INPUTS={RUNS}")
        return 0

    nebula = None
    if not args.lindhard_only:
        try:
            b = run_electron.Nebula().binary()
            nebula = (b, run_electron.Nebula().version(b))
            print(f"Nebula: {b} ({nebula[1]})")
            if (os.cpu_count() or 0) not in threads:
                print(f"note: Nebula runs on {os.cpu_count()} threads; add that count to --threads "
                      "for a like-for-like rate")
        except run_electron.NotConfigured as e:
            print(e)

    binary = scaling_binary()
    version = _version()
    rustc = subprocess.run(["rustc", "--version"], capture_output=True, text=True).stdout.strip() or None
    today = _dt.date.today().isoformat()
    SUMMARIES.mkdir(exist_ok=True)
    for p in problems:
        n = max(spec["batches"], int(round(p["histories"] * args.scale)))
        inp, materials = write_input(p, spec, cstool, n)
        load0 = load_average()
        lin = run_scaling(binary, inp, n, threads, args.repeat, args.table_threads)
        neb = run_nebula(p, spec, nebula[0], n) if nebula else None
        load1 = load_average()
        for r in lin["runs"]:
            print(f"{p['id']}: {r['threads']} threads, {r['electrons_per_s']:.4g} electrons/s, "
                  f"efficiency {r['efficiency']:.3f}, same report {r['identical_to_first']}")
        comparison = None
        if neb:
            neb.update({"version": nebula[1], "commit": run_electron.Nebula().commit(),
                        "build": run_electron.Nebula().build(),
                        "source": run_electron.Nebula.source_url,
                        "license": run_electron.Nebula.license_note})
            same = next((r for r in lin["runs"] if r["threads"] == neb["threads"]), None)
            comparison = {
                "threads": neb["threads"],
                "lindhard_electrons_per_s": same["electrons_per_s"] if same else None,
                "nebula_electrons_per_s": neb["electrons_per_s"],
                "electrons_per_s_ratio": (same["electrons_per_s"] / neb["electrons_per_s"]
                                          if same and neb["electrons_per_s"] else None),
                "note": "> 1: lindhard faster; transport only on both sides (lindhard after its table build, "
                        "Nebula's own Simulation time after loading its cstool material file)",
            }
            print(f"  Nebula: {neb['threads']} threads, {_fmt(neb['electrons_per_s'])} electrons/s")
        summary = {
            "format": FORMAT,
            "problem": p["id"],
            "date": today,
            "lindhard_version": version,
            "build": {"profile": "release (lto = fat, codegen-units = 1)", "rustc": rustc},
            "host": h,
            "load_average": {"start": load0, "end": load1},
            "materials": materials,
            "settings": {
                "energy_ev": p["energy_ev"],
                "element": p["element"],
                "seed": spec["seed"],
                "physics": spec["lindhard"],
                "tally": {"se_bse_split_ev": spec["split_ev"], "rmax_nm": p["rmax_nm"], "rbins": p["rbins"]},
            },
            "lindhard": lin,
            "nebula": neb,
            "comparison": comparison,
            "caveats": [
                "timings depend on the hardware, the build (compiler, flags) and the load of the machine; "
                "compare ratios within one summary, not absolute numbers across machines",
                "the physics differs between the codes (run_electron.py mismatches: full vs single-pole Penn, "
                "ELSEPA vs Thomas-Fermi Yukawa Mott, phonon and recoil losses), so the work per history differs",
                "Nebula always runs on all logical CPUs (no thread option)",
            ],
        }
        path = SUMMARIES / f"bench-electron-{p['id']}.json"
        path.write_text(json.dumps(_round(summary), indent=2, ensure_ascii=False) + "\n")
        print(f"  wrote {path.relative_to(lindhard_cli.REPO)}")
        if not lin["deterministic"]:
            lindhard_cli.die(f"{p['id']}: the tally report differs between thread counts")
    return 0


def _version() -> str:
    """`lindhard <workspace version> (<git describe>)`, as `lindhard --version`."""
    m = re.search(r'^version = "([^"]+)"', (lindhard_cli.REPO / "Cargo.toml").read_text(), re.M)
    d = run_electron._git(str(lindhard_cli.REPO), "describe", "--always", "--dirty")
    return f"lindhard {m.group(1) if m else '?'} ({d or 'unknown'})"


if __name__ == "__main__":
    sys.exit(main())
