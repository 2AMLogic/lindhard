# Host description (no host name, user or network identity)


def _cpu_model() -> str | None:
    if sys.platform.startswith("linux"):
        try:
            for line in Path("/proc/cpuinfo").read_text().splitlines():
                if line.startswith("model name"):
                    return line.split(":", 1)[1].strip()
        except OSError:
            return None
    if sys.platform == "darwin":
        out = subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True, text=True)
        return out.stdout.strip() or None
    return None


def _physical_cores() -> int | None:
    if sys.platform.startswith("linux"):
        try:
            cores, phys, core = set(), None, None
            for line in Path("/proc/cpuinfo").read_text().splitlines():
                k, _, v = line.partition(":")
                k = k.strip()
                if k == "physical id":
                    phys = v.strip()
                elif k == "core id":
                    core = v.strip()
                elif not line.strip():
                    if core is not None:
                        cores.add((phys, core))
                    phys = core = None
            if core is not None:
                cores.add((phys, core))
            return len(cores) or None
        except OSError:
            return None
    if sys.platform == "darwin":
        out = subprocess.run(["sysctl", "-n", "hw.physicalcpu"], capture_output=True, text=True)
        return int(out.stdout) if out.stdout.strip().isdigit() else None
    return None


def load_average() -> float | None:
    return round(os.getloadavg()[0], 2) if hasattr(os, "getloadavg") else None


def host() -> dict:
    return {
        "system": platform.system(),
        "machine": platform.machine(),
        "cpu_model": _cpu_model(),
        "logical_cpus": os.cpu_count(),
        "physical_cores": _physical_cores(),
    }


# ---------------------------------------------------------------------------
# lindhard side


def scaling_binary() -> Path:
    env = os.environ.get("LINDHARD_SCALING_BIN")
    if env:
        return Path(env)
    proc = subprocess.run(
        ["cargo", "build", "--release", "-p", "lindhard", "--example", "electron_scaling",
         "--message-format=json"],
        cwd=lindhard_cli.REPO, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, text=True,
    )
    if proc.returncode != 0:
        lindhard_cli.die("building the electron_scaling example failed; run the cargo command by hand")
    for line in proc.stdout.splitlines():
        try:
            msg = json.loads(line)
        except json.JSONDecodeError:
            continue
        if msg.get("reason") == "compiler-artifact" and msg.get("executable") \
                and msg["target"]["name"] == "electron_scaling":
            return Path(msg["executable"])
    lindhard_cli.die("could not find the electron_scaling executable in cargo's output")
    raise AssertionError


def write_input(problem: dict, spec: dict, cstool: Path, histories: int) -> tuple[Path, dict]:
    """lindhard's matched input of `run_electron.py` for one problem, written to
    `RUNS/<problem>/input.toml` (the layout `LINDHARD_BENCH_ELECTRON_INPUTS`
    expects). Returns the path and the material note of the summary."""
    mat = run_electron.cstool_material(cstool, problem["cstool_material"])
    work = RUNS / problem["id"]
    work.mkdir(parents=True, exist_ok=True)
    elf = run_electron.write_elf(problem, mat, work)
    path = work / "input.toml"
    path.write_text(run_electron.lindhard_input(problem, spec, mat, elf, spec["seed"], histories))
    materials = {
        "cstool_source": "https://github.com/Nebula-simulator/cstool",
        "cstool_commit": run_electron._git(str(cstool), "rev-parse", "HEAD") or "unknown",
        "parameter_file": f"data/materials/{problem['cstool_material']}",
        "parameter_file_sha256": mat["yaml_sha256"],
        "elf_file": f"data/materials/{mat['df'].relative_to(mat['yaml'].parent)}",
        "elf_file_sha256": mat["df_sha256"],
    }
    return path, materials


def run_scaling(binary: Path, inp: Path, histories: int, threads: list[int], repeat: int,
                table_threads: int) -> dict:
    cmd = [str(binary), "--input", str(inp), "--histories", str(histories),
           "--threads", ",".join(map(str, threads)), "--repeat", str(repeat),
           "--table-threads", str(table_threads)]
    proc = subprocess.run(cmd, capture_output=True, text=True)
    if proc.returncode not in (0, 1) or not proc.stdout.strip():
        lindhard_cli.die(f"electron_scaling failed on {inp}:\n{proc.stderr}")
    out = json.loads(proc.stdout)
    for k in ("input", "problem"):
        out.pop(k, None)  # local paths
    return out


# ---------------------------------------------------------------------------
# Nebula side (timing only; the physics comparison is run_electron.py's)


def run_nebula(problem: dict, spec: dict, binary: Path, histories: int) -> dict:
    """Nebula's CPU build on the primaries and geometry of run_electron.py,
    with the deposit stream discarded (/dev/null), so that what is timed is the
    simulation and not our reading of its output. Returns process wall time,
    Nebula's own "Simulation" and loading times, and its version line."""
    neb = run_electron.Nebula()
    work = RUNS / "nebula" / problem["id"]
    work.mkdir(parents=True, exist_ok=True)
    tri = work / "geometry.tri"
    tri.write_text(neb.geometry())
    pri = work / "primaries.pri"
    rec = struct.Struct("=7f2i")
    with open(pri, "wb") as f:
        for i in range(histories):
            f.write(rec.pack(0.0, 0.0, neb.START_Z_NM, 0.0, 0.0, -1.0, problem["energy_ev"], i, 0))
    mat = Path(os.environ["NEBULA_MATERIALS"]) / problem["nebula_material"]
    if not mat.is_file():
        lindhard_cli.die(f"Nebula material file {mat} not found (NEBULA_MATERIALS)")
    log = work / "stderr.log"
    cmd = [str(binary), f"--seed={spec['seed']}", f"--detect-filename={work / 'detected.bin'}",
           f"--deposit-filename={os.devnull}", str(tri), str(pri), str(mat)]
    t0 = time.perf_counter()
    with open(log, "w") as err:
        proc = subprocess.run(cmd, cwd=work, stdout=subprocess.DEVNULL, stderr=err)
    wall = time.perf_counter() - t0
    if proc.returncode != 0:
        lindhard_cli.die(f"Nebula failed on {problem['id']} (exit {proc.returncode}); see {log}")
    text = log.read_text()
    timings = {m.group(1).strip(): float(m.group(2))
               for m in re.finditer(r"^\s*([A-Za-z ]+):\s*([0-9.]+)\s*$", text, re.M)}
    threads = re.search(r"Creating (\d+) CPU drivers", text)
    version = next((ln for ln in text.splitlines() if ln.startswith("This is Nebula version")), "")
    sim = timings.get("Simulation")
    return {
        "histories": histories,
        "threads": int(threads.group(1)) if threads else None,
        "process_wall_s": wall,
        "simulation_s": sim,
        "loading_materials_s": timings.get("Loading materials"),
        "electrons_per_s": histories / sim if sim else None,
        "nebula_reports": version.replace("This is ", "") or None,
        "material_file": problem["nebula_material"],
        "material_sha256": run_electron.sha256(mat),
    }


