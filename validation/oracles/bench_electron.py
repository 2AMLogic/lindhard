#!/usr/bin/env python3
"""Electron engine benchmarks on the matched problems of #150 (#152;
docs/benchmarks.md, "Electron engine"; CONTRIBUTING.md, "Oracles").

For each problem of `electron_problems.json` (electrons at normal incidence
into bulk Si and bulk Cu at 1, 5 and 20 keV) this script

1. writes lindhard's matched input from the user's cstool clone, exactly as
   `run_electron.py` does (same physics, same material files read at run
   time; into the gitignored `validation/oracle-runs/electron-bench/`);
2. runs `lindhard/examples/electron_scaling.rs` on it: the cross-section
   tables are built once and timed separately, then the same histories run on
   1, 2, ... N threads, each `--repeat` times; the example records wall time,
   electrons/s, speedup and parallel efficiency, and the SHA-256 of the full
   tally report at every thread count (it fails if they differ: determinism);
3. if Nebula is configured (the variables of `run_electron.py`), times
   Nebula's CPU build (`nebula_cpu_edep`, run unmodified, outside this tree)
   on the same primaries, with its deposit stream discarded;
4. writes one scalar summary per problem,
   `validation/oracles/summaries/bench-electron-<problem>.json`
   (format `lindhard-electron-bench/1`): versions, settings, host (CPU model
   and core counts, load average; no host name) and the timings. No oracle
   table, input or output is written there.

`--update-docs` rebuilds the electron tables of `docs/benchmarks.md` from the
committed summaries (this file's and #150's) without running anything.

Configuration (environment):

    CSTOOL_SRC      cstool clone (required; see run_electron.py)
    NEBULA_BIN, NEBULA_MATERIALS, NEBULA_SRC, NEBULA_VERSION, NEBULA_COMMIT,
    NEBULA_BUILD    as for run_electron.py (optional)
    LINDHARD_SCALING_BIN
                    the `electron_scaling` example binary; default: built
                    with `cargo build --release -p lindhard --example
                    electron_scaling` (CARGO_BUILD_JOBS limits the jobs)

Nebula's CPU driver starts one thread per hardware thread and has no option
to change that (source/cpu_energydep.cpp, std::thread::hardware_concurrency at
commit a50a8e8), so its timing is always at all logical CPUs; for a like-for-
like rate include that count in `--threads`. Its own "Simulation" time comes
from a progress loop that sleeps one second at a time, so it has a resolution
of about one second: use enough histories for runs of tens of seconds.

Benchmarks belong on a quiet machine. The summary records the load average at
the start and end of every problem; numbers taken under load are marked so in
the docs.

Usage:
    validation/oracles/bench_electron.py --threads 1,2,4 --repeat 3
    validation/oracles/bench_electron.py --problem e_5keV_si --scale 0.2 --lindhard-only
    validation/oracles/bench_electron.py --write-inputs      # inputs only (for the Criterion bench)
    validation/oracles/bench_electron.py --update-docs [--check]
"""

