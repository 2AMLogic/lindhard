// The form model of the simulator page and its lindhard TOML input file.
//
// `toToml` writes a setup as the run description of `docs/cli.md`; `fromToml`
// reads such a file back into a setup. Only the keys the form exposes
// round-trip: any other key is rejected with a message naming it, never
// dropped. Units follow the file (eV, nm, degrees, g/cm^3).
//
// A setup:
//   { beam:   { ion, massAmu|null, energyEv, tiltDeg },
//     layers: [{ name, thicknessNm|null (semi-infinite, last layer only),
//                densityGcm3|null (null: the tabulated density of a pure
//                element), elements: [{ symbol, fraction,
//                eDEv|null, eBEv|null, eSEv|null }] }],   // null: table default
//     physics: { potential, stopping, followRecoils, primaryCutoffEv,
//                recoilCutoffEv },
//     run:    { ions, seed },
//     tally:  { depthBinNm, depthBins } }
//
// Plain ES module with no dependencies, so the page, the Worker and the Node
// tests share it.

export const POTENTIALS = ["zbl", "kr-c", "moliere", "lenz-jensen"];
export const STOPPINGS = ["lindhard-scharff", "bethe-bloch", "equipartition-ls-or"];
export const MAX_IONS = 1000000;
const NAME_RE = /^[A-Za-z0-9_-]+$/;

export class ModelError extends Error {}

export function defaultSetup() {
  return {
    beam: { ion: "B", massAmu: null, energyEv: 10000, tiltDeg: 7 },
    layers: [
      {
        name: "Si",
        thicknessNm: null,
        densityGcm3: null,
        elements: [{ symbol: "Si", fraction: 1, eDEv: 15, eBEv: null, eSEv: null }],
      },
    ],
    physics: {
      potential: "zbl",
      stopping: "lindhard-scharff",
      followRecoils: false,
      primaryCutoffEv: 5,
      recoilCutoffEv: 2,
    },
    run: { ions: 10000, seed: 1 },
    tally: { depthBinNm: 1, depthBins: 500 },
  };
}

// ---- writing ---------------------------------------------------------------

const float = (x) => (Number.isInteger(x) && Math.abs(x) < 1e15 ? `${x}.0` : String(x));
const str = (s) => JSON.stringify(s);

function elementInline(e) {
  const parts = [`symbol = ${str(e.symbol)}`, `atom_fraction = ${float(e.fraction)}`];
  if (e.eDEv != null) parts.push(`e_d_ev = ${float(e.eDEv)}`);
  if (e.eBEv != null) parts.push(`e_b_ev = ${float(e.eBEv)}`);
  if (e.eSEv != null) parts.push(`e_s_ev = ${float(e.eSEv)}`);
  return `{ ${parts.join(", ")} }`;
}

/** The TOML text of a setup. Does not validate; see `validate`. */
export function toToml(s) {
  const out = [
    "# Generated by the lindhard simulator page. Run it unchanged with:",
    "#   lindhard run <this file> --out out/",
    "",
    "[beam]",
    `ion = ${str(s.beam.ion)}`,
  ];
  if (s.beam.massAmu != null) out.push(`mass_amu = ${float(s.beam.massAmu)}`);
  out.push(`energy_ev = ${float(s.beam.energyEv)}`, `tilt_deg = ${float(s.beam.tiltDeg)}`, "");

  for (const l of s.layers) {
    out.push(`[materials.${l.name}]`);
    if (l.densityGcm3 != null) out.push(`density_g_cm3 = ${float(l.densityGcm3)}`);
    out.push("elements = [", ...l.elements.map((e) => `  ${elementInline(e)},`), "]", "");
  }

  out.push("[target]");
  const last = s.layers[s.layers.length - 1];
  const finite = last && last.thicknessNm == null ? s.layers.slice(0, -1) : s.layers;
  if (last && last.thicknessNm == null) out.push(`substrate = ${str(last.name)}`);
  out.push("");
  for (const l of finite) {
    out.push("[[target.layers]]", `material = ${str(l.name)}`, `thickness_nm = ${float(l.thicknessNm)}`, "");
  }

  const p = s.physics;
  out.push(
    "[physics]",
    `potential = ${str(p.potential)}`,
    `stopping = ${str(p.stopping)}`,
    'free_path = "constant"',
    `follow_recoils = ${p.followRecoils}`,
    `primary_cutoff_ev = ${float(p.primaryCutoffEv)}`,
    `recoil_cutoff_ev = ${float(p.recoilCutoffEv)}`,
    "",
    "[run]",
    `ions = ${s.run.ions}`,
    `seed = ${s.run.seed}`,
    "",
    "[tally]",
    `depth_bin_nm = ${float(s.tally.depthBinNm)}`,
    `depth_bins = ${s.tally.depthBins}`,
    "",
  );
  return out.join("\n");
}

// ---- validation ------------------------------------------------------------

const num = (x) => typeof x === "number" && Number.isFinite(x);

/**
 * Problems that would make the engine refuse the setup, as
 * `{ path, message }`. `elements` is the table of `elements_json()` (rows with
 * `symbol`, `density_g_cm3`, `default_displacement_ev`,
 * `default_surface_binding_ev`).
 */
export function validate(s, elements) {
  const bad = [];
  const add = (path, message) => bad.push({ path, message });
  const table = new Map(elements.map((e) => [e.symbol, e]));

  if (!table.has(s.beam.ion)) add("beam.ion", `unknown element "${s.beam.ion}"`);
  if (s.beam.massAmu != null && !(num(s.beam.massAmu) && s.beam.massAmu > 0)) {
    add("beam.mass", "the mass must be positive");
  }
  if (!(num(s.beam.energyEv) && s.beam.energyEv > 0)) add("beam.energy", "the energy must be positive");
  if (!(num(s.beam.tiltDeg) && s.beam.tiltDeg >= 0 && s.beam.tiltDeg < 90)) {
    add("beam.tilt", "the incidence angle must be in [0, 90) degrees");
  }

  if (s.layers.length === 0) add("layers", "the target needs at least one layer");
  const names = new Set();
  s.layers.forEach((l, i) => {
    const at = `layers[${i}]`;
    if (!NAME_RE.test(l.name)) add(`${at}.name`, "use letters, digits, - and _ in a layer name");
    else if (names.has(l.name)) add(`${at}.name`, `the layer name "${l.name}" is used twice`);
    names.add(l.name);
    const isLast = i === s.layers.length - 1;
    if (l.thicknessNm == null) {
      if (!isLast) add(`${at}.thickness`, "only the last layer can be semi-infinite");
    } else if (!(num(l.thicknessNm) && l.thicknessNm > 0)) {
      add(`${at}.thickness`, "the thickness must be positive");
    }
    if (l.elements.length === 0) add(`${at}.elements`, "the composition is empty");
    const seen = new Set();
    l.elements.forEach((e, j) => {
      const eat = `${at}.elements[${j}]`;
      const row = table.get(e.symbol);
      if (!row) {
        add(`${eat}.symbol`, `unknown element "${e.symbol}"`);
        return;
      }
      if (seen.has(e.symbol)) add(`${eat}.symbol`, `${e.symbol} appears twice in ${l.name}`);
      seen.add(e.symbol);
      if (!(num(e.fraction) && e.fraction > 0)) add(`${eat}.fraction`, "the amount must be positive");
      if ((e.eDEv ?? row.default_displacement_ev) == null) {
        add(`${eat}.eD`, `${e.symbol} has no tabulated displacement energy: enter one`);
      }
      if ((e.eSEv ?? row.default_surface_binding_ev) == null) {
        add(`${eat}.eS`, `${e.symbol} has no tabulated surface binding energy: enter one`);
      }
    });
    const pure = l.elements.length === 1;
    if (l.densityGcm3 != null) {
      if (!(num(l.densityGcm3) && l.densityGcm3 > 0)) add(`${at}.density`, "the density must be positive");
    } else if (!pure) {
      add(`${at}.density`, "a compound needs a density");
    } else if (table.get(l.elements[0].symbol)?.density_g_cm3 == null) {
      add(`${at}.density`, `${l.elements[0].symbol} has no tabulated density: enter one`);
    }
  });

  const p = s.physics;
  if (!POTENTIALS.includes(p.potential)) add("physics.potential", "unknown potential");
  if (!STOPPINGS.includes(p.stopping)) add("physics.stopping", "unknown stopping model");
  if (!(num(p.primaryCutoffEv) && p.primaryCutoffEv > 0)) add("physics.primaryCutoff", "the cutoff must be positive");
  if (!(num(p.recoilCutoffEv) && p.recoilCutoffEv > 0)) add("physics.recoilCutoff", "the cutoff must be positive");
  if (!Number.isInteger(s.run.ions) || s.run.ions < 1 || s.run.ions > MAX_IONS) {
    add("run.ions", `the ion count must be an integer from 1 to ${MAX_IONS}`);
  }
  if (!Number.isSafeInteger(s.run.seed) || s.run.seed < 0) add("run.seed", "the seed must be a non-negative integer");
  if (!(num(s.tally.depthBinNm) && s.tally.depthBinNm > 0)) add("tally.depthBin", "the bin width must be positive");
  if (!Number.isInteger(s.tally.depthBins) || s.tally.depthBins < 1) add("tally.depthBins", "the bin count must be a positive integer");
  return bad;
}

// ---- reading ---------------------------------------------------------------

/**
 * Parse the TOML subset a lindhard input uses: tables, arrays of tables,
 * dotted and quoted keys, strings, numbers, booleans, arrays and inline
 * tables, comments. Dates and multi-line strings are not accepted.
 */
export function parseToml(text) {
  let i = 0;
  const root = {};
  const fail = (msg) => {
    const line = text.slice(0, i).split("\n").length;
    throw new ModelError(`line ${line}: ${msg}`);
  };
  const skipSpace = () => {
    while (i < text.length && (text[i] === " " || text[i] === "\t")) i++;
  };
  const skipComment = () => {
    if (text[i] === "#") while (i < text.length && text[i] !== "\n") i++;
  };
  const skipAll = () => {
    for (;;) {
      skipSpace();
      skipComment();
      if (text[i] === "\n" || text[i] === "\r") i++;
      else return;
    }
  };
  const endOfLine = () => {
    skipSpace();
    skipComment();
    if (i < text.length && text[i] !== "\n" && text[i] !== "\r") fail(`unexpected "${text[i]}"`);
  };

  function key() {
    skipSpace();
    if (text[i] === '"') return stringValue();
    const m = /^[A-Za-z0-9_-]+/.exec(text.slice(i));
    if (!m) fail("expected a key");
    i += m[0].length;
    return m[0];
  }
  function dottedKey() {
    const path = [key()];
    for (skipSpace(); text[i] === "."; skipSpace()) {
      i++;
      path.push(key());
    }
    return path;
  }
  function stringValue() {
    const start = i++;
    let raw = '"';
    while (i < text.length && text[i] !== '"') {
      if (text[i] === "\n") fail("unterminated string");
      if (text[i] === "\\") raw += text[i++];
      raw += text[i++];
    }
    if (text[i] !== '"') fail("unterminated string");
    i++;
    raw += '"';
    try {
      return JSON.parse(raw);
    } catch {
      i = start;
      return fail("unsupported escape in a string");
    }
  }
  function value() {
    skipSpace();
    const c = text[i];
    if (c === '"') {
      if (text.startsWith('"""', i)) fail("multi-line strings are not supported");
      return stringValue();
    }
    if (c === "[") {
      i++;
      const arr = [];
      for (;;) {
        skipAll();
        if (text[i] === "]") {
          i++;
          return arr;
        }
        arr.push(value());
        skipAll();
        if (text[i] === ",") i++;
        else if (text[i] !== "]") fail('expected "," or "]"');
      }
    }
    if (c === "{") {
      i++;
      const t = {};
      for (skipSpace(); text[i] !== "}"; skipSpace()) {
        const path = dottedKey();
        skipSpace();
        if (text[i] !== "=") fail('expected "="');
        i++;
        assign(t, path, value());
        skipSpace();
        if (text[i] === ",") i++;
        else if (text[i] !== "}") fail('expected "," or "}"');
      }
      i++;
      return t;
    }
    const m = /^[^\s,\]}#]+/.exec(text.slice(i));
    if (!m) return fail("expected a value");
    i += m[0].length;
    const v = m[0];
    if (v === "true") return true;
    if (v === "false") return false;
    if (/^[+-]?(\d[\d_]*)(\.\d[\d_]*)?([eE][+-]?\d+)?$/.test(v)) return Number(v.replaceAll("_", ""));
    if (/^[+-]?(inf|nan)$/.test(v)) fail("inf and nan are not accepted");
    return fail(`cannot read the value "${v}"`);
  }
  function assign(table, path, v) {
    let t = table;
    for (const k of path.slice(0, -1)) {
      t = t[k] ??= {};
      if (typeof t !== "object" || Array.isArray(t)) fail(`"${k}" is not a table`);
    }
    const k = path[path.length - 1];
    if (k in t) fail(`duplicate key "${path.join(".")}"`);
    t[k] = v;
  }

  let current = root;
  for (skipAll(); i < text.length; skipAll()) {
    if (text[i] === "[") {
      const array = text[i + 1] === "[";
      i += array ? 2 : 1;
      const path = dottedKey();
      skipSpace();
      if (!text.startsWith(array ? "]]" : "]", i)) fail("unterminated table header");
      i += array ? 2 : 1;
      endOfLine();
      let t = root;
      for (const k of path.slice(0, -1)) {
        t = t[k] ??= {};
        if (Array.isArray(t)) t = t[t.length - 1];
      }
      const last = path[path.length - 1];
      if (array) {
        if (!Array.isArray((t[last] ??= []))) fail(`"${last}" is not an array of tables`);
        current = {};
        t[last].push(current);
      } else {
        if (last in t) fail(`duplicate table [${path.join(".")}]`);
        current = t[last] = {};
      }
    } else {
      const path = dottedKey();
      skipSpace();
      if (text[i] !== "=") fail('expected "="');
      i++;
      assign(current, path, value());
      endOfLine();
    }
  }
  return root;
}

const isTable = (x) => x !== null && typeof x === "object" && !Array.isArray(x);

function only(obj, allowed, where) {
  if (!isTable(obj)) throw new ModelError(`${where} must be a table`);
  for (const k of Object.keys(obj)) {
    if (!allowed.includes(k)) {
      throw new ModelError(
        `${where}: the key "${k}" is not supported by this page. ` +
          "It is valid in a lindhard input file: run that file with lindhard-cli instead.",
      );
    }
  }
}

function need(obj, k, where, type = "number") {
  if (!(k in obj)) throw new ModelError(`${where}: missing "${k}"`);
  return typed(obj[k], `${where}.${k}`, type);
}
function opt(obj, k, where, type = "number") {
  return k in obj ? typed(obj[k], `${where}.${k}`, type) : null;
}
function typed(v, where, type) {
  if (type === "number" ? typeof v !== "number" : typeof v !== type) {
    throw new ModelError(`${where} must be a ${type}`);
  }
  return v;
}

/**
 * Read a lindhard input file into a setup. Throws `ModelError` for a syntax
 * error, a key the form cannot represent or a value of the wrong type.
 */
export function fromToml(text) {
  const t = parseToml(text);
  only(t, ["beam", "materials", "target", "physics", "run", "tally"], "the file");

  const b = t.beam ?? {};
  only(b, ["ion", "mass_amu", "energy_ev", "tilt_deg"], "[beam]");
  const beam = {
    ion: need(b, "ion", "[beam]", "string"),
    massAmu: opt(b, "mass_amu", "[beam]"),
    energyEv: need(b, "energy_ev", "[beam]"),
    tiltDeg: opt(b, "tilt_deg", "[beam]") ?? 0,
  };

  const materials = t.materials ?? {};
  only(materials, Object.keys(materials), "[materials]");
  const specOf = (name) => {
    const m = materials[name];
    if (m === undefined) {
      // An element symbol: the pure element at its tabulated density.
      return { densityGcm3: null, elements: [{ symbol: name, fraction: 1, eDEv: null, eBEv: null, eSEv: null }] };
    }
    const w = `[materials.${name}]`;
    only(m, ["density_g_cm3", "elements"], w);
    if (!Array.isArray(m.elements)) throw new ModelError(`${w}: "elements" must be an array`);
    return {
      densityGcm3: opt(m, "density_g_cm3", w),
      elements: m.elements.map((e, j) => {
        const ew = `${w}.elements[${j}]`;
        if (isTable(e) && "mass_fraction" in e) {
          throw new ModelError(`${ew}: mass_fraction is not supported by this page; give atom_fraction`);
        }
        only(e, ["symbol", "atom_fraction", "e_d_ev", "e_b_ev", "e_s_ev"], ew);
        return {
          symbol: need(e, "symbol", ew, "string"),
          fraction: opt(e, "atom_fraction", ew) ?? 1,
          eDEv: opt(e, "e_d_ev", ew),
          eBEv: opt(e, "e_b_ev", ew),
          eSEv: opt(e, "e_s_ev", ew),
        };
      }),
    };
  };

  const tg = t.target ?? {};
  only(tg, ["substrate", "layers"], "[target]");
  const refs = [];
  for (const [j, l] of (tg.layers ?? []).entries()) {
    const w = `[[target.layers]] #${j + 1}`;
    only(l, ["material", "thickness_nm"], w);
    refs.push({ material: need(l, "material", w, "string"), thicknessNm: need(l, "thickness_nm", w) });
  }
  if ("substrate" in tg) refs.push({ material: typed(tg.substrate, "target.substrate", "string"), thicknessNm: null });
  const used = new Map();
  const layers = refs.map((r) => {
    const n = (used.get(r.material) ?? 0) + 1;
    used.set(r.material, n);
    return { name: n === 1 ? r.material : `${r.material}-${n}`, thicknessNm: r.thicknessNm, ...specOf(r.material) };
  });
  const referenced = new Set(refs.map((r) => r.material));
  for (const name of Object.keys(materials)) {
    if (!referenced.has(name)) throw new ModelError(`[materials.${name}] is not used by any layer`);
  }

  const p = t.physics ?? {};
  only(
    p,
    ["potential", "stopping", "free_path", "follow_recoils", "primary_cutoff_ev", "recoil_cutoff_ev", "energies"],
    "[physics]",
  );
  const freePath = opt(p, "free_path", "[physics]", "string");
  if (freePath != null && freePath !== "constant") {
    throw new ModelError('[physics]: only free_path = "constant" is supported by this page');
  }
  const physics = {
    potential: opt(p, "potential", "[physics]", "string") ?? "zbl",
    stopping: opt(p, "stopping", "[physics]", "string") ?? "lindhard-scharff",
    followRecoils: opt(p, "follow_recoils", "[physics]", "boolean") ?? true,
    primaryCutoffEv: need(p, "primary_cutoff_ev", "[physics]"),
    recoilCutoffEv: need(p, "recoil_cutoff_ev", "[physics]"),
  };
  // [physics.energies.<Sym>] overrides the material's own value in every layer
  // that holds the element; the form keeps the energies per layer element.
  const energies = p.energies ?? {};
  only(energies, Object.keys(energies), "[physics.energies]");
  for (const [sym, e] of Object.entries(energies)) {
    const w = `[physics.energies.${sym}]`;
    only(e, ["e_d_ev", "e_b_ev", "e_s_ev"], w);
    let hit = false;
    for (const l of layers) {
      for (const el of l.elements) {
        if (el.symbol !== sym) continue;
        hit = true;
        for (const [k, f] of [["e_d_ev", "eDEv"], ["e_b_ev", "eBEv"], ["e_s_ev", "eSEv"]]) {
          const v = opt(e, k, w);
          if (v != null) el[f] = v;
        }
      }
    }
    if (!hit) throw new ModelError(`${w} applies to no element of the target`);
  }

  const r = t.run ?? {};
  only(r, ["ions", "seed"], "[run]");
  const run = { ions: need(r, "ions", "[run]"), seed: need(r, "seed", "[run]") };

  const ta = t.tally ?? {};
  only(ta, ["depth_bin_nm", "depth_bins"], "[tally]");
  const tally = {
    depthBinNm: opt(ta, "depth_bin_nm", "[tally]") ?? 1,
    depthBins: opt(ta, "depth_bins", "[tally]") ?? 1000,
  };

  return { beam, layers, physics, run, tally };
}
